def migrate():
    added, skipped = 0, 0
    for (name, cat, equip, diff, intro, steps, tips, sets, reps) in NEW_EXERCISES:
        exists = db.query("SELECT id FROM rehab_exercises WHERE name = %s", (name,), one=True)
        if exists:
            skipped += 1
            continue
        db.execute(
            "INSERT INTO rehab_exercises (name, category, equipment, difficulty, intro, steps, tips, "
            "default_sets, default_reps, default_weight, is_custom) "
            "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,0,0)",
            (name, cat, equip, diff, intro, steps, tips, sets, reps))
        added += 1
    total = db.query("SELECT COUNT(*) AS cnt FROM rehab_exercises WHERE is_custom=0", one=True)["cnt"]
    print(f"[OK] 新增 {added} 个动作，跳过已存在 {skipped} 个，当前内置动作共 {total} 个")


if __name__ == "__main__":
    migrate()
